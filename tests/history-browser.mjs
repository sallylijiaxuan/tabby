import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage();
 await page.addInitScript(()=>{if(!localStorage.getItem('history-seeded')){localStorage.setItem('tabby-bill',JSON.stringify({items:[{id:1,name:'Pasta',price:60,quantity:1,people:[0]},{id:2,name:'Fish',price:40,quantity:1,people:[1]}],people:['You','Alex'],tax:10,tip:20,restaurant:'First dinner'}));localStorage.setItem('history-seeded','1')}});
 await page.goto('http://127.0.0.1:5174');
 await expect(page.getByLabel('Bill name',{exact:true})).toHaveValue('First dinner');
 await page.getByRole('button',{name:'New split',exact:true}).click();
 await page.getByRole('button',{name:'Enter items manually'}).click();
 await expect(page.locator('.people-list .person')).toHaveCount(1);
 await expect(page.locator('.people-list .person')).toContainText('You');
 await expect(page.getByLabel('Tax amount',{exact:true})).toHaveValue('');
 await expect(page.getByLabel('Tip amount',{exact:true})).toHaveValue('');
 await page.getByLabel('Bill name',{exact:true}).fill('Second dinner');
 const price=page.getByLabel('New item price',{exact:true});await price.fill('25');await price.press('Enter');
 await page.getByRole('button',{name:'Assign New item to You',exact:true}).click();
 await page.getByRole('button',{name:'Open past bills',exact:true}).click();
 await expect(page.locator('.history-entry')).toHaveCount(2);
 await page.getByRole('button').filter({hasText:'First dinner'}).click();
 await expect(page.getByLabel('Bill name',{exact:true})).toHaveValue('First dinner');
 await expect(page.locator('.people-list .person')).toHaveCount(2);
 await expect(page.getByRole('button',{name:'Assign Pasta to You',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect(page.getByLabel('Tax amount',{exact:true})).toHaveValue('10.00');
 await expect(page.locator('.grand-total')).toContainText('$130.00');
 await page.reload();await expect(page.getByLabel('Bill name',{exact:true})).toHaveValue('First dinner');
 await page.getByRole('button',{name:'Open past bills',exact:true}).click();
 await expect(page.locator('.history-entry')).toHaveCount(2);
 await page.getByRole('button').filter({hasText:'Second dinner'}).click();
 await expect(page.getByLabel('New item price',{exact:true})).toHaveValue('25');
 await expect(page.locator('.people-list .person')).toHaveCount(1);
 await page.getByRole('button',{name:'New split',exact:true}).click();
 const chooserPromise=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Start with a receipt'}).click();
 const chooser=await chooserPromise;
 await expect(page.locator('.people-list .person')).toHaveCount(1);
 await expect(page.getByLabel('Items subtotal',{exact:true})).toHaveText('$0.00');
 await chooser.setFiles([]);
 await page.getByRole('button',{name:'Open past bills',exact:true}).click();
 await expect(page.locator('.history-entry')).toHaveCount(2);
 await page.getByRole('button').filter({hasText:'First dinner'}).click();
 await expect(page.getByLabel('Pasta price',{exact:true})).toHaveValue('60');
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('tabby-history')).length),2);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open past bills',exact:true}).click();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/private/tmp/tabby-history-mobile.png',fullPage:false});
 console.log('Passed: legacy current-bill preservation, guest reset for manual and photo splits, history without duplicates, reopening assignments and amounts, reload persistence, canceled photo selection, and mobile history.');
}finally{await browser.close()}
